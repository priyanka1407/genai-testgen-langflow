"""
Human-in-the-loop governance via JIRA - idempotent and approval-safe.

sync()          create-or-update: one issue per test case, tracked in state by tc_id ->
                issue key + content hash. Rerunning never duplicates; only changed
                content is pushed. Obsolete cases get the 'obsolete' label.
pull_reviews()  reads status + description back from JIRA:
                  * approved / rejected / pending per test case
                  * reviewer EDITS to the description are parsed back into the
                    test case and win over the generated version
approval safety An approval is tied to the content that was approved. If the pipeline
                later pushes new content for that case, the approval is void until the
                issue is re-approved (and, if JIRA_REOPEN_TRANSITION_ID is set, the issue
                is transitioned back to review automatically).

Clients
  RestJiraClient  real JIRA (REST v2).  Env: JIRA_URL, JIRA_USER, JIRA_API_TOKEN, JIRA_PROJECT,
                  JIRA_ISSUE_TYPE, JIRA_APPROVED_STATUS, JIRA_REJECTED_STATUS, JIRA_REOPEN_TRANSITION_ID
  FileJiraClient  dry-run: a local JSON "JIRA" (state/fake_jira.json). Approve/reject with
                  python -m testgen.jira_publisher approve TC-REQ-PAY-001-01 ...
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Protocol

from .models import TestCase, TestStep

APPROVED = os.getenv("JIRA_APPROVED_STATUS", "Approved")
REJECTED = os.getenv("JIRA_REJECTED_STATUS", "Rejected")
PENDING = "Pending Review"
BASE_LABELS = ["ai-generated"]


def _h(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()[:16]


def norm_desc(s: str | None) -> str:
    """JIRA may rewrite line endings / trailing spaces - ignore that when detecting edits."""
    return "\n".join(line.rstrip() for line in (s or "").replace("\r\n", "\n").strip().split("\n"))


# ---------------------------------------------------------------- rendering / parsing
def render_description(tc: TestCase, flags: list[str] | None = None) -> str:
    steps = "\n".join(f"# {s.action} -> _expected:_ {s.expected}" for s in tc.steps)
    pre = "\n".join(f"* {p}" for p in tc.preconditions) or "* none"
    data = "\n".join(f"* {f.name} ({f.kind}, {'valid' if f.valid else 'INVALID'}): {f.rule}"
                     + (f" = {f.fixed_value}" if f.fixed_value else "")
                     + (f" from {f.reference}" if f.reference else "") for f in tc.data_fields) or "* none"
    cons = "\n".join(f"* {c.left} {c.op} {c.right}{'' if c.must_hold else ' (deliberately violated)'}"
                     for c in tc.constraints)
    setup = "\n".join(f"* {s.count} x {s.entity}: {s.description}"
                      + (f" (total {s.total_field} = {s.total_value})" if s.total_field else "") for s in tc.setup)
    note = f"\n{{color:red}}Reviewer attention: {', '.join(flags)}{{color}}\n" if flags else ""
    return (
        f"h3. Requirement\n{tc.req_id} (covers criteria {tc.covers_criteria})\n"
        f"h3. Type\n{tc.test_type} / {tc.technique} / layer={tc.layer} / outcome={tc.expected_outcome}\n"
        f"h3. Preconditions\n{pre}\n"
        f"h3. Steps\n{steps}\n"
        f"h3. Expected result\n{tc.expected_result}\n"
        f"h3. Test data recipe\n{data}\n"
        + (f"h3. Data rules\n{cons}\n" if cons else "")
        + (f"h3. Setup data\n{setup}\n" if setup else "")
        + f"{note}----\n_Generated by the GenAI test design pipeline. Edit Preconditions / Steps / "
          "Expected result directly - edits are pulled back into the test suite._"
    )


def parse_description(desc: str, base: TestCase) -> TestCase:
    """Read reviewer edits (preconditions, steps, expected result) back into the test case."""
    sections: dict[str, list[str]] = {}
    current = None
    for line in norm_desc(desc).split("\n"):
        m = re.match(r"h3\.\s*(.+)", line)
        if m:
            current = m.group(1).strip().lower()
            sections[current] = []
        elif line.startswith("----"):
            current = None
        elif current:
            sections[current].append(line)
    update: dict = {}
    if "preconditions" in sections:
        pre = [l[1:].strip() for l in sections["preconditions"] if l.startswith("*")]
        update["preconditions"] = [p for p in pre if p.lower() != "none"]
    if "steps" in sections:
        steps = []
        for l in sections["steps"]:
            if not l.startswith("#"):
                continue
            action, _, expected = l[1:].strip().partition("-> _expected:_")
            steps.append(TestStep(step=len(steps) + 1, action=action.strip(), expected=expected.strip()))
        if steps:
            update["steps"] = steps
    if "expected result" in sections:
        text = "\n".join(sections["expected result"]).strip()
        if text:
            update["expected_result"] = text
    return base.model_copy(update=update)


def build_fields(tc: TestCase, flags: list[str] | None = None) -> dict:
    project = os.getenv("JIRA_PROJECT", "QA")
    labels = BASE_LABELS + ["pending-review", tc.req_id, tc.test_type] + (["needs-revision"] if flags else [])
    return {
        "project": {"key": project},
        "issuetype": {"name": os.getenv("JIRA_ISSUE_TYPE", "Task")},
        "summary": f"[{tc.tc_id}] {tc.title}"[:250],
        "description": render_description(tc, flags),
        "labels": labels,
        "priority": {"name": {"P1": "High", "P2": "Medium", "P3": "Low"}[tc.priority]},
    }


# ---------------------------------------------------------------- clients
class JiraClient(Protocol):
    def create(self, fields: dict) -> str: ...
    def update(self, key: str, fields: dict) -> None: ...
    def reopen(self, key: str) -> None: ...
    def get_many(self, keys: list[str]) -> dict[str, dict]: ...   # key -> {status, description}


class FileJiraClient:
    """A local JSON stand-in for JIRA used in dry-run mode, demos and tests."""

    def __init__(self, path: str | Path):
        self.path = Path(path)
        self.data = json.loads(self.path.read_text(encoding="utf-8")) if self.path.exists() \
            else {"seq": 0, "issues": {}}

    def _save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text(json.dumps(self.data, indent=2), encoding="utf-8")

    def create(self, fields: dict) -> str:
        self.data["seq"] += 1
        key = f"DRY-{self.data['seq']}"
        self.data["issues"][key] = {"fields": fields, "status": PENDING,
                                    "updated": datetime.now(timezone.utc).isoformat()}
        self._save()
        return key

    def update(self, key: str, fields: dict) -> None:
        self.data["issues"][key]["fields"].update(fields)
        self.data["issues"][key]["updated"] = datetime.now(timezone.utc).isoformat()
        self._save()

    def reopen(self, key: str) -> None:
        self.data["issues"][key]["status"] = PENDING
        self._save()

    def get_many(self, keys: list[str]) -> dict[str, dict]:
        return {k: {"status": i["status"], "description": i["fields"].get("description", "")}
                for k, i in self.data["issues"].items() if k in keys}

    # helpers for demos / tests (simulate the reviewer)
    def set_status(self, key: str, status: str) -> None:
        self.data["issues"][key]["status"] = status
        self._save()

    def edit_description(self, key: str, description: str) -> None:
        self.data["issues"][key]["fields"]["description"] = description
        self._save()


class RestJiraClient:
    def __init__(self):
        import requests

        self.base = os.environ["JIRA_URL"].rstrip("/")
        self.s = requests.Session()
        token = os.getenv("JIRA_API_TOKEN") or os.getenv("JIRA_PAT")
        if os.getenv("JIRA_USER"):
            self.s.auth = (os.environ["JIRA_USER"], token)          # Cloud: email + API token
        else:
            self.s.headers["Authorization"] = f"Bearer {token}"     # Server/DC: personal access token
        self.reopen_transition = os.getenv("JIRA_REOPEN_TRANSITION_ID")

    def create(self, fields: dict) -> str:
        r = self.s.post(f"{self.base}/rest/api/2/issue", json={"fields": fields}, timeout=30)
        r.raise_for_status()
        return r.json()["key"]

    def update(self, key: str, fields: dict) -> None:
        fields = {k: v for k, v in fields.items() if k not in ("project", "issuetype")}
        self.s.put(f"{self.base}/rest/api/2/issue/{key}", json={"fields": fields}, timeout=30).raise_for_status()

    def reopen(self, key: str) -> None:
        if self.reopen_transition:
            self.s.post(f"{self.base}/rest/api/2/issue/{key}/transitions",
                        json={"transition": {"id": self.reopen_transition}}, timeout=30).raise_for_status()

    def get_many(self, keys: list[str]) -> dict[str, dict]:
        # One GET per issue: works on JIRA Cloud (where /rest/api/2/search has been retired) and Server/DC
        out: dict[str, dict] = {}
        for key in keys:
            r = self.s.get(f"{self.base}/rest/api/2/issue/{key}", params={"fields": "status,description"}, timeout=30)
            if r.status_code == 404:
                continue   # deleted in JIRA - nothing to pull
            r.raise_for_status()
            f = r.json()["fields"]
            out[key] = {"status": f["status"]["name"], "description": f.get("description") or ""}
        return out


# ---------------------------------------------------------------- sync
def pull_reviews(client: JiraClient, jmap: dict, cases: dict[str, TestCase]) -> dict[str, dict]:
    """Returns tc_id -> {status: approved|rejected|pending, jira_status, edited_case (TestCase|None)}."""
    keys = {e["key"]: tid for tid, e in jmap.items() if not e.get("obsolete")}
    remote = client.get_many(list(keys))
    out: dict[str, dict] = {}
    for key, info in remote.items():
        tid = keys[key]
        entry = jmap[tid]
        jstatus = info["status"]
        if jstatus == APPROVED:
            # approval only counts if nothing was pushed since the reviewer last saw it
            status = "pending" if entry.get("needs_reapproval") else "approved"
        elif jstatus == REJECTED:
            status = "rejected"
        else:
            status = "pending"
            entry["needs_reapproval"] = False  # issue is back in review - the reset was observed
        edited = None
        if tid in cases and _h(norm_desc(info["description"])) != entry.get("desc_hash"):
            candidate = parse_description(info["description"], cases[tid])
            if candidate.model_dump() != cases[tid].model_dump():
                edited = candidate
            entry["desc_hash"] = _h(norm_desc(info["description"]))
        out[tid] = {"status": status, "jira_status": jstatus, "issue_key": key, "edited_case": edited}
    return out


def sync(cases: list[TestCase], obsolete_ids: list[str], client: JiraClient, jmap: dict,
         flags: dict[str, list[str]] | None = None, skip_ids: set[str] | frozenset = frozenset()) -> list[dict]:
    flags = flags or {}
    results = []
    for tc in cases:
        fields = build_fields(tc, flags.get(tc.tc_id))
        content = _h(json.dumps({k: fields[k] for k in ("summary", "description", "labels", "priority")},
                                sort_keys=True))
        entry = jmap.get(tc.tc_id)
        if tc.tc_id in skip_ids and entry:
            op = "kept-reviewer-edit"
        elif not entry or entry.get("obsolete"):
            key = client.create(fields)
            jmap[tc.tc_id] = {"key": key, "hash": content, "desc_hash": _h(norm_desc(fields["description"]))}
            op = "created"
        elif entry["hash"] == content:
            op = "unchanged"
        else:
            client.update(entry["key"], fields)
            client.reopen(entry["key"])
            entry.update(hash=content, desc_hash=_h(norm_desc(fields["description"])), needs_reapproval=True)
            op = "updated"
        results.append({"tc_id": tc.tc_id, "issue_key": jmap[tc.tc_id]["key"], "op": op})
    for tid in obsolete_ids:
        entry = jmap.get(tid)
        if entry and not entry.get("obsolete"):
            client.update(entry["key"], {"labels": BASE_LABELS + ["obsolete"]})
            entry["obsolete"] = True
            results.append({"tc_id": tid, "issue_key": entry["key"], "op": "obsoleted"})
    return results


def get_client(real: bool, state_dir: str | Path) -> JiraClient:
    return RestJiraClient() if real else FileJiraClient(Path(state_dir) / "fake_jira.json")


# ---------------------------------------------------------------- reviewer simulator CLI (dry-run)
def main() -> None:
    ap = argparse.ArgumentParser(description="Simulate reviewer actions on the dry-run JIRA")
    ap.add_argument("action", choices=["approve", "reject", "approve-all", "list"])
    ap.add_argument("tc_ids", nargs="*")
    ap.add_argument("--state", default="state")
    a = ap.parse_args()
    st = json.loads((Path(a.state) / "state.json").read_text(encoding="utf-8"))
    jmap = st["jira"]["dry_run"]
    client = FileJiraClient(Path(a.state) / "fake_jira.json")
    if a.action == "list":
        for tid, e in sorted(jmap.items()):
            print(f"{tid:28} {e['key']:8} {client.data['issues'][e['key']]['status']}")
        return
    ids = [t for t, e in jmap.items() if not e.get("obsolete")] if a.action == "approve-all" else a.tc_ids
    status = REJECTED if a.action == "reject" else APPROVED
    for tid in ids:
        client.set_status(jmap[tid]["key"], status)
        print(f"{tid} -> {status}")


if __name__ == "__main__":
    main()
